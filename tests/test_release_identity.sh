#!/usr/bin/env bash
set -euo pipefail
root=${1:?repository root required}
mkdir -p "$root/build"
work=$(mktemp -d "$root/build/release-identity.XXXXXX")
trap 'rm -rf -- "$work"' EXIT
mkdir -p "$work/repo/scripts" "$work/bin"
cp "$root/scripts/check_release_identity.sh" "$root/scripts/release_version.sh" "$work/repo/scripts/"
cat >"$work/bin/git" <<'GIT'
#!/usr/bin/env bash
set -euo pipefail
shift 2
case "$1" in
  rev-parse)
    if [[ "$2" == --show-toplevel ]]; then printf '%s\n' "$TEST_IDENTITY_ROOT"; else printf '0123456789\n'; fi ;;
  status) printf '%s' "${TEST_IDENTITY_DIRTY:-}" ;;
  tag) [[ "$2" == --points-at ]] || exit 91; printf '%s\n' "${TEST_IDENTITY_TAGS:-}" ;;
  cat-file) printf '%s\n' "${TEST_IDENTITY_TYPE:-commit}" ;;
  symbolic-ref) [[ "${TEST_IDENTITY_SYMBOLIC:-0}" == 1 ]] ;;
  *) printf 'unexpected Git mutation: %s\n' "$*" >&2; exit 92 ;;
esac
GIT
chmod +x "$work/bin/git"
export PATH="$work/bin:$PATH" TEST_IDENTITY_ROOT="$work/repo"
unset LONEJSON_VERSION_OVERRIDE
check() { bash "$work/repo/scripts/check_release_identity.sh" "$@"; }
reject() {
  local expected=$1; shift
  if "$@" >"$work/rejected" 2>&1; then printf 'invalid release identity accepted\n' >&2; exit 1; fi
  grep -F "$expected" "$work/rejected" >/dev/null
}
TEST_IDENTITY_TAGS=v1.2.3 check | grep -F 'Release identity verified: v1.2.3 0123456789'
reject 'exactly one lightweight' check
TEST_IDENTITY_TAGS=$'v1.2.3\nv2.3.4' reject 'exactly one lightweight' check
TEST_IDENTITY_TAGS=v1.2.3 TEST_IDENTITY_TYPE=tag reject 'must be lightweight' check
TEST_IDENTITY_TAGS=v1.2.3 TEST_IDENTITY_SYMBOLIC=1 reject 'must not be symbolic' check
TEST_IDENTITY_TAGS=v1.2.3 TEST_IDENTITY_DIRTY=' M source.c' reject 'commit or remove' check
TEST_IDENTITY_TAGS=v1.2.3 TEST_IDENTITY_DIRTY='?? new.c' reject 'commit or remove' check
TEST_IDENTITY_TAGS=v1.2.3 LONEJSON_VERSION_OVERRIDE=1.2.3 reject 'remove LONEJSON_VERSION_OVERRIDE' check
TEST_IDENTITY_ROOT="$work" reject 'owning Git checkout' check
TEST_IDENTITY_TAGS=v1.2.3 reject 'accepts no arguments' check extra
# Preserve generated bytes when the real Make entrypoint rejects this worktree.
printf retained >"$work/sentinel"
TEST_IDENTITY_ROOT="$root" TEST_IDENTITY_DIRTY=' M source.c' TEST_IDENTITY_TAGS=v1.2.3 \
  reject 'commit or remove' make -s -C "$root" lifecycle-version-contract
[[ $(cat "$work/sentinel") == retained ]]
